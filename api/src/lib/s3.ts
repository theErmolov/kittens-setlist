import { S3Client, PutObjectCommand, GetObjectCommand } from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';

const s3 = new S3Client({});
const BUCKET = process.env.RECEIPTS_BUCKET ?? 'kittens-receipts';

/** Presigned PUT URL the browser uses to upload a receipt directly to S3. */
export async function getReceiptUploadUrl(key: string, contentType: string): Promise<string> {
  const command = new PutObjectCommand({ Bucket: BUCKET, Key: key, ContentType: contentType });
  return getSignedUrl(s3, command, { expiresIn: 600 });
}

/** Presigned GET URL the browser uses to view/download a stored receipt. */
export async function getReceiptDownloadUrl(key: string): Promise<string> {
  const command = new GetObjectCommand({ Bucket: BUCKET, Key: key });
  return getSignedUrl(s3, command, { expiresIn: 600 });
}
